"""Run the conflict-set evaluation and write eval/results/.

  uv run python eval/run.py            # all four configs + threshold sweep (real model)
  uv run python eval/run.py --quick    # all four configs, no sweep

Needs no API key. The embedding model is cached in eval/.cache (downloaded once).
Numbers are only ever written from what this script measured.
"""

import argparse
import json
import platform
import sys
from datetime import UTC, datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

from harness import Dataset, as_dicts, run_all, sweep, sweep_recency

from ctxbook import __version__
from ctxbook.config import Settings
from ctxbook.embeddings.fastembed_embedder import FastembedEmbedder

HERE = Path(__file__).parent
DATASET = HERE / "datasets" / "conflicts.jsonl"
RESULTS = HERE / "results"
CACHE = HERE / ".cache" / "models"
SWEEP = [0.50, 0.55, 0.60, 0.65, 0.70, 0.75, 0.80, 0.85]
RECENCY = [0.0, 0.01, 0.02, 0.05, 0.1, 0.2]


def _pct(value: float) -> str:
    return f"{value * 100:.1f}%"


def _markdown(
    meta: dict[str, object], results: list[dict], rows: list[dict], recency: list[dict]
) -> str:
    out = [
        "# ctxbook evaluation: conflict set",
        "",
        f"- Dataset: `eval/datasets/conflicts.jsonl` ({meta['cases']} cases, "
        f"{meta['update_cases']} with a changed fact), synthetic, seed-generated by "
        "`eval/build_conflicts.py`; sha256 `" + str(meta["dataset_sha256"])[:16] + "…`",
        f"- Embedding model: {meta['embedding_model']}; ctxbook {meta['ctxbook']}",
        f"- Machine: {meta['machine']}; run {meta['date']}",
        "- Conflict configs use an **oracle** client AI (always resolves correctly), so they "
        "measure ctxbook's detection and retrieval, not an LLM's judgement.",
        "",
        "| Config | Recall@1 | Recall@5 | MRR | Stale@1 | Stale in top 5 | Save ms | Search ms |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in results:
        out.append(
            f"| {r['config']}. {r['label']} | {_pct(r['recall_at_1'])} | {_pct(r['recall_at_5'])}"
            f" | {r['mrr']:.3f} | {_pct(r['stale_at_1'])} | {_pct(r['stale_in_top_5'])}"
            f" | {r['save_ms_mean']:.1f} | {r['search_ms_mean']:.1f} |"
        )
    out += [
        "",
        "Conflict detection (configs c and d):",
        "",
        "| Config | Updates flagged | Missed | Merged as duplicate | False flags |",
        "|---|---|---|---|---|",
    ]
    for r in results:
        if r["detection"]:
            d = r["detection"]
            out.append(
                f"| {r['config']} | {_pct(d['updates_flagged'])} | {_pct(d['updates_missed'])}"
                f" | {_pct(d['updates_merged_as_duplicate'])} | {_pct(d['false_flag_rate'])} |"
            )
    if rows:
        out += [
            "",
            f"Threshold sweep (config c, duplicate threshold {rows[0]['duplicate_threshold']}):",
            "",
            "| Lower threshold | Flagged | Missed | False flags | Recall@1 | Stale@1 |",
            "|---|---|---|---|---|---|",
        ]
        for row in rows:
            out.append(
                f"| {row['similar_threshold']:.2f} | {_pct(row['updates_flagged'])}"
                f" | {_pct(row['updates_missed'])} | {_pct(row['false_flag_rate'])}"
                f" | {_pct(row['recall_at_1'])} | {_pct(row['stale_at_1'])} |"
            )
    if recency:
        out += [
            "",
            "Recency weight sweep (same weight in every mode; keyword-only = config d):",
            "",
            "| Weight | b R@1 | b Stale@1 | b Stale top 5 | c R@1 | c Stale@1 | c Stale top 5"
            " | d R@1 | d Stale@1 | d Stale top 5 |",
            "|---|---|---|---|---|---|---|---|---|---|",
        ]
        for row in recency:
            cells = " | ".join(
                _pct(row[f"{k}_{m}"])
                for k in "bcd"
                for m in ("recall_at_1", "stale_at_1", "stale_in_top_5")
            )
            out.append(f"| {row['recency_weight']:.2f} | {cells} |")
    return "\n".join(out) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--quick", action="store_true", help="skip the threshold sweep")
    args = parser.parse_args()

    dataset = Dataset.load(DATASET)
    embedder = FastembedEmbedder(CACHE)
    embedder.load()  # one model for every config (loading is not part of latency)

    def make_embedder() -> FastembedEmbedder:
        return embedder

    defaults = Settings()
    results = as_dicts(run_all(dataset, make_embedder))
    rows = (
        []
        if args.quick
        else sweep(dataset, make_embedder, SWEEP, duplicate=defaults.duplicate_threshold)
    )
    recency = [] if args.quick else sweep_recency(dataset, make_embedder, RECENCY)
    meta = {
        "date": datetime.now(UTC).isoformat(timespec="seconds"),
        "ctxbook": __version__,
        "embedding_model": embedder.model_name,
        "machine": f"{platform.system()} {platform.machine()}, Python {platform.python_version()}",
        "dataset_sha256": dataset.sha256,
        "cases": len(dataset.cases),
        "update_cases": sum(c["kind"] == "update" for c in dataset.cases),
        "settings": {
            "similar_threshold": defaults.similar_threshold,
            "duplicate_threshold": defaults.duplicate_threshold,
            "search_min_similarity": defaults.search_min_similarity,
            "recency_weight": defaults.recency_weight,
            "keyword_recency_weight": defaults.keyword_recency_weight,
        },
    }
    report = _markdown(meta, results, rows, recency)
    print(report)
    if args.quick:
        print("(--quick: results not written; run `make eval` for the full report)")
        return
    RESULTS.mkdir(exist_ok=True)
    payload = {"meta": meta, "results": results, "sweep": rows, "recency_sweep": recency}
    (RESULTS / "conflicts.json").write_text(json.dumps(payload, indent=2) + "\n")
    (RESULTS / "conflicts.md").write_text(report)


if __name__ == "__main__":
    main()
